-- NOM_DIAS_FESTIVOS por tipo de empleado + horarios especiales + oficinas
-- (diseño "Diseño de Tablas para Tramites RH.xlsx", Hoja 10).
--
-- Paso 1 de 2. NO borra APLICA_SEXO ni SOLO_SINDICALIZADOS: el backend publicado todavía las lee.
-- Se borran con AlterNomDiasFestivosDropViejas.sql cuando se publique el backend nuevo.
--
-- Reglas:
--   ID_FESTIVO            nueva PK (secuencia + trigger). FECHA_FESTIVO deja de ser única: un mismo día
--                         puede tener un festivo para unos y un horario especial para otros.
--   FECHA_FESTIVO         solo fecha (sin hora). Día que NO se trabaja, ya recorrido si hubo puente.
--   HORA_ENTRADA/SALIDA   'HH24:MI'. Ambas NULL = día completo de descanso; con alguna = el día se trabaja
--                         pero se permite llegar tarde / salir temprano (asamblea, desfile).
--   APLICA_BASE/CONFIANZA/CONTRATO   1 = ese tipo tiene el festivo (EMPLEADOS.ID_TIPOEMP B / C / T).
--   *_SEXO                NULL = ambos; 'F' / 'M' como EMPLEADOS.SEXO.
--   *_REQ_HIJOS           1 = exige tener hijos. Todavía no hay de dónde leerlo; las consultas lo ignoran.
--   NOM_DIAS_FESTIVOS_OFICINAS   oficinas (EMPLEADOS.LUGARTRAB) a las que aplica; sin renglones = todas.

ALTER TABLE NOM_DIAS_FESTIVOS ADD (
    ID_FESTIVO       NUMBER,
    HORA_ENTRADA     VARCHAR2(5),
    HORA_SALIDA      VARCHAR2(5),
    APLICA_BASE      NUMBER(1) DEFAULT 1 NOT NULL,
    BASE_SEXO        VARCHAR2(1),
    BASE_REQ_HIJOS   NUMBER(1) DEFAULT 0 NOT NULL,
    APLICA_CONFIANZA NUMBER(1) DEFAULT 1 NOT NULL,
    CONF_SEXO        VARCHAR2(1),
    CONF_REQ_HIJOS   NUMBER(1) DEFAULT 0 NOT NULL,
    APLICA_CONTRATO  NUMBER(1) DEFAULT 1 NOT NULL,
    CONT_SEXO        VARCHAR2(1),
    CONT_REQ_HIJOS   NUMBER(1) DEFAULT 0 NOT NULL
);

-- IDs para lo que ya existe, en orden de fecha.
MERGE INTO NOM_DIAS_FESTIVOS F
USING (SELECT ROWID RID, ROW_NUMBER() OVER (ORDER BY FECHA_FESTIVO) RN FROM NOM_DIAS_FESTIVOS) X
ON (F.ROWID = X.RID)
WHEN MATCHED THEN UPDATE SET F.ID_FESTIVO = X.RN;

-- Lo capturado hasta hoy aplicaba igual a todos los tipos.
UPDATE NOM_DIAS_FESTIVOS
   SET BASE_SEXO = APLICA_SEXO, CONF_SEXO = APLICA_SEXO, CONT_SEXO = APLICA_SEXO;
UPDATE NOM_DIAS_FESTIVOS
   SET APLICA_CONFIANZA = 0, APLICA_CONTRATO = 0
 WHERE SOLO_SINDICALIZADOS = 1;

-- La PK pasa de FECHA_FESTIVO a ID_FESTIVO; la fecha conserva un índice normal para los rangos.
ALTER TABLE NOM_DIAS_FESTIVOS DROP PRIMARY KEY DROP INDEX;
ALTER TABLE NOM_DIAS_FESTIVOS MODIFY (ID_FESTIVO NOT NULL);
ALTER TABLE NOM_DIAS_FESTIVOS ADD CONSTRAINT PK_NOM_DIAS_FESTIVOS PRIMARY KEY (ID_FESTIVO);
CREATE INDEX IX_NOM_DIAS_FEST_FECHA ON NOM_DIAS_FESTIVOS (FECHA_FESTIVO);

ALTER TABLE NOM_DIAS_FESTIVOS ADD (
    CONSTRAINT CK_NOM_DIAS_FEST_SOLOFECHA CHECK (FECHA_FESTIVO = TRUNC(FECHA_FESTIVO)),
    CONSTRAINT CK_NOM_DIAS_FEST_HENT CHECK (REGEXP_LIKE(HORA_ENTRADA, '^([01][0-9]|2[0-3]):[0-5][0-9]$')),
    CONSTRAINT CK_NOM_DIAS_FEST_HSAL CHECK (REGEXP_LIKE(HORA_SALIDA, '^([01][0-9]|2[0-3]):[0-5][0-9]$')),
    CONSTRAINT CK_NOM_DIAS_FEST_APBASE CHECK (APLICA_BASE IN (0, 1)),
    CONSTRAINT CK_NOM_DIAS_FEST_BSEXO CHECK (BASE_SEXO IN ('F', 'M')),
    CONSTRAINT CK_NOM_DIAS_FEST_BHIJOS CHECK (BASE_REQ_HIJOS IN (0, 1)),
    CONSTRAINT CK_NOM_DIAS_FEST_APCONF CHECK (APLICA_CONFIANZA IN (0, 1)),
    CONSTRAINT CK_NOM_DIAS_FEST_CFSEXO CHECK (CONF_SEXO IN ('F', 'M')),
    CONSTRAINT CK_NOM_DIAS_FEST_CFHIJOS CHECK (CONF_REQ_HIJOS IN (0, 1)),
    CONSTRAINT CK_NOM_DIAS_FEST_APCONT CHECK (APLICA_CONTRATO IN (0, 1)),
    CONSTRAINT CK_NOM_DIAS_FEST_CTSEXO CHECK (CONT_SEXO IN ('F', 'M')),
    CONSTRAINT CK_NOM_DIAS_FEST_CTHIJOS CHECK (CONT_REQ_HIJOS IN (0, 1))
);

-- La secuencia arranca después del último ID asignado arriba.
DECLARE
    V_INICIO NUMBER;
BEGIN
    SELECT NVL(MAX(ID_FESTIVO), 0) + 1 INTO V_INICIO FROM NOM_DIAS_FESTIVOS;
    EXECUTE IMMEDIATE 'CREATE SEQUENCE SEQ_NOM_DIAS_FESTIVOS START WITH ' || V_INICIO || ' INCREMENT BY 1 NOCACHE';
END;
/

CREATE OR REPLACE TRIGGER TRG_NOM_DIAS_FESTIVOS_BI
BEFORE INSERT ON NOM_DIAS_FESTIVOS
FOR EACH ROW
WHEN (NEW.ID_FESTIVO IS NULL)
BEGIN
    :NEW.ID_FESTIVO := SEQ_NOM_DIAS_FESTIVOS.NEXTVAL;
END;
/

-- Oficinas (EMPLEADOS.LUGARTRAB) a las que aplica un festivo u horario especial. Sin renglones = todas.
CREATE TABLE NOM_DIAS_FESTIVOS_OFICINAS (
    ID_FESTIVO NUMBER NOT NULL,
    ID_OFICINA NUMBER NOT NULL,
    CONSTRAINT PK_NOM_DIAS_FEST_OFICINAS PRIMARY KEY (ID_FESTIVO, ID_OFICINA),
    CONSTRAINT FK_NOM_DIAS_FEST_OFI_FESTIVO FOREIGN KEY (ID_FESTIVO)
        REFERENCES NOM_DIAS_FESTIVOS (ID_FESTIVO) ON DELETE CASCADE
);

-- Reglas de los casos de uso de la hoja.
-- Día de las Madres: base todos; confianza y contrato solo mujeres con hijos.
UPDATE NOM_DIAS_FESTIVOS
   SET APLICA_BASE = 1, BASE_SEXO = NULL, BASE_REQ_HIJOS = 0,
       APLICA_CONFIANZA = 1, CONF_SEXO = 'F', CONF_REQ_HIJOS = 1,
       APLICA_CONTRATO = 1, CONT_SEXO = 'F', CONT_REQ_HIJOS = 1
 WHERE FECHA_FESTIVO = DATE '2026-05-10';
-- Día del Padre: solo base, todos.
UPDATE NOM_DIAS_FESTIVOS
   SET APLICA_BASE = 1, BASE_SEXO = NULL, BASE_REQ_HIJOS = 0,
       APLICA_CONFIANZA = 0, CONF_SEXO = NULL, CONF_REQ_HIJOS = 0,
       APLICA_CONTRATO = 0, CONT_SEXO = NULL, CONT_REQ_HIJOS = 0
 WHERE FECHA_FESTIVO = DATE '2026-06-19';
-- Día del Hombre: solo base, hombres.
UPDATE NOM_DIAS_FESTIVOS
   SET APLICA_BASE = 1, BASE_SEXO = 'M', BASE_REQ_HIJOS = 0,
       APLICA_CONFIANZA = 0, CONF_SEXO = NULL, CONF_REQ_HIJOS = 0,
       APLICA_CONTRATO = 0, CONT_SEXO = NULL, CONT_REQ_HIJOS = 0
 WHERE FECHA_FESTIVO IN (DATE '2025-11-24', DATE '2026-11-23');
-- Día de la Mujer ya quedaba 'F' para los tres tipos con la copia de APLICA_SEXO.

COMMIT;
