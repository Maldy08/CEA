-- Limpia los datos de PRUEBA del Sistema de Trámites (vacaciones, permisos, justificantes).
-- NO toca catálogos (RH_CAT_TIPOS_TRAMITE, RH_CAT_ESTATUS, NOM_DIAS_FESTIVOS), ni NOM_VACAEMP / NOM_INCAP / NOM_PERMISOS viejas,
-- ni viáticos. Orden = hijos primero por las FK hacia NOM_TRAMITES.

DELETE FROM NOM_VACAEMP_D
 WHERE ID_VACAEMP IN (SELECT ID_VACAEMP FROM NOM_VACAEMP_M);
DELETE FROM NOM_VACAEMP_M;
DELETE FROM NOM_PERMISOS_JUSTIFICANTES;
DELETE FROM NOM_INCAPACIDADES WHERE ORIGEN_REGISTRO = 'T';
DELETE FROM NOM_TRAMITES_BITACORA;
DELETE FROM NOM_TRAMITES;

-- Revisar conteos (todos deben dar 0) y luego COMMIT o ROLLBACK.
