SELECT 'NOM_TRAMITES_BITACORA', COUNT(*) FROM NOM_TRAMITES_BITACORA UNION ALL
SELECT 'NOM_VACAEMP_M', COUNT(*) FROM NOM_VACAEMP_M UNION ALL
SELECT 'NOM_VACAEMP_D', COUNT(*) FROM NOM_VACAEMP_D UNION ALL
SELECT 'NOM_PERMISOS_JUSTIFICANTES', COUNT(*) FROM NOM_PERMISOS_JUSTIFICANTES;

