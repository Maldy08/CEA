-- Detalle de los trámites de permisos y justificantes (diseño "Diseño de Tablas para TRamites RH", pestaña
-- nom_permisos_justificantes, versión del 2026-11-11). Uno por trámite (NOM_TRAMITES, TIPO_TRAMITE 3 = PERMISOS,
-- 4 = JUSTIFICANTES). El empleado sale de NOM_TRAMITES.ID_EMPLEADO.
--
--   TIPO_INCIDENCIA   1 PERMISO CON GOCE
--                     2 PERMISO SIN GOCE
--                     3 JUSTIFICACION ENTRADA
--                     4 JUSTIFICACION SALIDA
--                     5 JUSTIFICACION NO CHECADA ENTRADA
--                     6 JUSTIFICACION NO CHECADA SALIDA
--                     7 JUSTIFICACION NO CHECADA
--   FECHA_INICIO/FIN  DATE (puede llevar hora). Un solo día: FECHA_FIN = FECHA_INICIO.
--   ID_EMPLEADO_CUBRE relevo opcional (cve_empleado_cubre del diseño; mismo nombre que NOM_VACAEMP_M).

CREATE TABLE NOM_PERMISOS_JUSTIFICANTES (
    ID_PERMISO_JUSTIFICANTE NUMBER(12)    NOT NULL,
    ID_TRAMITE              NUMBER(12)    NOT NULL,
    TIPO_INCIDENCIA         NUMBER(1)     NOT NULL,
    FECHA_INICIO            DATE          NOT NULL,
    FECHA_FIN               DATE          NOT NULL,
    JUSTIFICACION_MOTIVO    VARCHAR2(500) NOT NULL,
    ID_EMPLEADO_CUBRE       NUMBER(4),
    CONSTRAINT PK_NOM_PERM_JUST PRIMARY KEY (ID_PERMISO_JUSTIFICANTE),
    CONSTRAINT UK_NOM_PERM_JUST_TRAMITE UNIQUE (ID_TRAMITE),
    CONSTRAINT FK_NOM_PERM_JUST_TRAMITE FOREIGN KEY (ID_TRAMITE) REFERENCES NOM_TRAMITES (ID_TRAMITE),
    CONSTRAINT FK_NOM_PERM_JUST_CUBRE FOREIGN KEY (ID_EMPLEADO_CUBRE) REFERENCES EMPLEADOS (EMPLEADO),
    CONSTRAINT CK_NOM_PERM_JUST_TIPO CHECK (TIPO_INCIDENCIA BETWEEN 1 AND 7),
    CONSTRAINT CK_NOM_PERM_JUST_FECHAS CHECK (FECHA_FIN >= FECHA_INICIO)
);

CREATE SEQUENCE SEQ_NOM_PERMISOS_JUSTIFICANTES START WITH 1 INCREMENT BY 1 NOCACHE;

CREATE OR REPLACE TRIGGER TRG_NOM_PERM_JUST_BI
BEFORE INSERT ON NOM_PERMISOS_JUSTIFICANTES
FOR EACH ROW
WHEN (NEW.ID_PERMISO_JUSTIFICANTE IS NULL)
BEGIN
    SELECT SEQ_NOM_PERMISOS_JUSTIFICANTES.NEXTVAL INTO :NEW.ID_PERMISO_JUSTIFICANTE FROM DUAL;
END;
/

COMMENT ON TABLE NOM_PERMISOS_JUSTIFICANTES IS 'Detalle de trámites de permisos/justificantes (NOM_TRAMITES tipo 3 y 4)';
COMMENT ON COLUMN NOM_PERMISOS_JUSTIFICANTES.TIPO_INCIDENCIA IS '1 PERMISO CON GOCE, 2 PERMISO SIN GOCE, 3 JUSTIF. ENTRADA, 4 JUSTIF. SALIDA, 5 JUSTIF. NO CHECADA ENTRADA, 6 JUSTIF. NO CHECADA SALIDA, 7 JUSTIF. NO CHECADA';
