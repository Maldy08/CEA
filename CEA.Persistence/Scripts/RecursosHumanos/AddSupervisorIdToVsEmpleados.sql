-- Exposes EMPLEADOS.SUPERVISOR_ID in VS_EMPLEADOS (requires AddSupervisorIdToEmpleados.sql).
-- Same definition as before plus SUPERVISOR_ID at the end.
CREATE OR REPLACE FORCE VIEW "CEA"."VS_EMPLEADOS" ("ACTIVO", "FRECUENCIA", "EMPLEADO", "PATERNO", "MATERNO", "NOMBRE", "ID_PUE", "DESCRIPCION_PUESTO", "DEPTOUE", "DESCRIPCION_DEPTO", "DEPTOCOMI", "DEPTOPPTO", "OBRA", "NOMBRE_COMPLETO", "MUNICIPIO", "OFICINA", "NIVEL", "LUGARTRAB", "CORREO", "SUPERVISOR_ID") AS
  SELECT
    A.ACTIVO,
    NVL(C.hits, 0) AS FRECUENCIA,
    A.EMPLEADO,
    A.PATERNO,
    A.MATERNO,
    A.NOMBRE,
    A.ID_PUE,
    B.DESCRIPCION AS DESCRIPCION_PUESTO,
    A.DEPTOUE,
    CC.DESCRIPCION AS DESCRIPCION_DEPTO,
    A.DEPTOCOMI,
    A.DEPTOPPTO,
    A.OBRA,
    A.NOMBRE || ' ' || A.PATERNO || ' ' || A.MATERNO AS NOMBRE_COMPLETO,
    A.MUNICIPIO,
    A.LUGARTRAB AS OFICINA,
    A.NIVEL,
    A.LUGARTRAB,
    A.CORREO_INST,
    A.SUPERVISOR_ID
FROM
    EMPLEADOS A
    LEFT JOIN (
        SELECT * FROM (
            SELECT z.*
            FROM oficios_frecuencia z
            WHERE z.TIPO = 1
            ORDER BY z.hits DESC
        )
        WHERE ROWNUM <= 10
    ) C ON A.empleado = C.ID_EMPOEXT
    JOIN NOM_PUESTOS B ON A.ID_PUE = B.ID_PUE
    JOIN DEPTOS_UE CC ON A.DEPTOCOMI = CC.ID_CEA
WHERE
    A.ACTIVO IN ('V', 'C')
ORDER BY
    2 DESC,
    3
