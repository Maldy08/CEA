-- Detalle del trámite de vacaciones (diseño "Diseño de Tablas para Tramites RH.xlsx", pestaña nom_vacaemp).
-- NOM_VACAEMP (la tabla vieja de movimientos) NO se toca.
--
-- NOM_VACAEMP_M   encabezado: una solicitud de vacaciones por trámite (NOM_TRAMITES).
--   DIAS_SOLICITADOS   días hábiles del rango FDESDE-FHASTA.
--   FECHA_REGRESO      primer día de regreso al trabajo.
--   ID_EMPLEADO_CUBRE  relevo opcional.
-- NOM_VACAEMP_D   desglose por periodo vacacional, mismas columnas que NOM_VACAEMP.
--   PERVAC             periodo de origen del saldo, 'AAAA-N' (ej. '2025-2'), como NOM_VACAEMP.PERVAC.
--   DIASVAC            días que se toman de ese periodo.
--   DIASXDISF          días que le quedan a ese periodo después de la solicitud.
--   NOMOV              número de movimiento en NOM_VACAEMP; NULL mientras no se aplique.
--   FDESDE/FHASTA      opcionales: el cálculo actual no reparte fechas por periodo.
--
-- Tipos numéricos de días como en NOM_VACAEMP (NUMBER(3), enteros).

CREATE TABLE NOM_VACAEMP_M (
    ID_VACAEMP        NUMBER(12)   NOT NULL,
    ID_TRAMITE        NUMBER(12)   NOT NULL,
    ANO               NUMBER(4)    NOT NULL,
    FOLIO             VARCHAR2(25) NOT NULL,
    NOEMP             NUMBER(4)    NOT NULL,
    DIAS_SOLICITADOS  NUMBER(3)    NOT NULL,
    FDESDE            DATE         NOT NULL,
    FHASTA            DATE         NOT NULL,
    FECHA_REGRESO     DATE,
    ID_EMPLEADO_CUBRE NUMBER(4),
    CONSTRAINT PK_NOM_VACAEMP_M PRIMARY KEY (ID_VACAEMP),
    CONSTRAINT FK_NOM_VACAEMP_M_TRAMITE FOREIGN KEY (ID_TRAMITE) REFERENCES NOM_TRAMITES (ID_TRAMITE),
    CONSTRAINT FK_NOM_VACAEMP_M_EMP FOREIGN KEY (NOEMP) REFERENCES EMPLEADOS (EMPLEADO),
    CONSTRAINT FK_NOM_VACAEMP_M_CUBRE FOREIGN KEY (ID_EMPLEADO_CUBRE) REFERENCES EMPLEADOS (EMPLEADO),
    CONSTRAINT CK_NOM_VACAEMP_M_RANGO CHECK (FHASTA >= FDESDE)
);

CREATE INDEX IX_NOM_VACAEMP_M_TRAMITE ON NOM_VACAEMP_M (ID_TRAMITE);
CREATE INDEX IX_NOM_VACAEMP_M_EMP ON NOM_VACAEMP_M (NOEMP, FDESDE);

CREATE SEQUENCE SEQ_NOM_VACAEMP_M START WITH 1 INCREMENT BY 1 NOCACHE;

CREATE OR REPLACE TRIGGER TRG_NOM_VACAEMP_M_BI
BEFORE INSERT ON NOM_VACAEMP_M
FOR EACH ROW
WHEN (NEW.ID_VACAEMP IS NULL)
BEGIN
    SELECT SEQ_NOM_VACAEMP_M.NEXTVAL INTO :NEW.ID_VACAEMP FROM DUAL;
END;
/

CREATE TABLE NOM_VACAEMP_D (
    ID_VACAEMP NUMBER(12) NOT NULL,
    NOEMP      NUMBER(4)  NOT NULL,
    ANO        NUMBER(4)  NOT NULL,
    NOMOV      NUMBER(4),
    FDESDE     DATE,
    FHASTA     DATE,
    DIASVAC    NUMBER(3)  NOT NULL,
    PERVAC     VARCHAR2(6) NOT NULL,
    DIASXDISF  NUMBER(3)  NOT NULL,
    CONSTRAINT PK_NOM_VACAEMP_D PRIMARY KEY (ID_VACAEMP, PERVAC),
    CONSTRAINT FK_NOM_VACAEMP_D_M FOREIGN KEY (ID_VACAEMP) REFERENCES NOM_VACAEMP_M (ID_VACAEMP),
    CONSTRAINT FK_NOM_VACAEMP_D_EMP FOREIGN KEY (NOEMP) REFERENCES EMPLEADOS (EMPLEADO),
    CONSTRAINT CK_NOM_VACAEMP_D_PERVAC CHECK (REGEXP_LIKE(PERVAC, '^[0-9]{4}-[12]$'))
);

CREATE INDEX IX_NOM_VACAEMP_D_EMP ON NOM_VACAEMP_D (NOEMP, PERVAC);
