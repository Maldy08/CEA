-- Catálogo de días festivos compartido: nómina (SP_ANALIZAR_*), vacaciones (next-tramites-cea) y Checador.Web.
-- FECHA_FESTIVO sigue siendo el día que NO se trabaja (ya recorrido si hubo puente); la PK se queda en ella
-- porque los SPs hacen SELECT ... INTO por fecha (un solo festivo por día).
--   FECHA_OFICIAL        fecha oficial cuando se recorrió por puente; NULL = no se movió.
--   APLICA_SEXO          NULL = todos; 'F' / 'M' = solo ese sexo (mismos valores que EMPLEADOS.SEXO).
--   SOLO_SINDICALIZADOS  reservada por si un día solo aplica al personal de base; hoy NULL = todos.
--   ACTIVO               1 = vigente, 0 = dado de baja sin borrarlo.
ALTER TABLE NOM_DIAS_FESTIVOS ADD (
    FECHA_OFICIAL       DATE,
    APLICA_SEXO         VARCHAR2(1),
    SOLO_SINDICALIZADOS NUMBER(1),
    ACTIVO              NUMBER(1) DEFAULT 1 NOT NULL,
    CONSTRAINT CK_NOM_DIAS_FEST_SEXO CHECK (APLICA_SEXO IN ('F', 'M')),
    CONSTRAINT CK_NOM_DIAS_FEST_SINDI CHECK (SOLO_SINDICALIZADOS IN (0, 1)),
    CONSTRAINT CK_NOM_DIAS_FEST_ACTIVO CHECK (ACTIVO IN (0, 1))
);

-- Navidad 2026 estaba capturada como 2023.
UPDATE NOM_DIAS_FESTIVOS SET FECHA_FESTIVO = DATE '2026-12-25' WHERE FECHA_FESTIVO = DATE '2023-12-25';

-- Festivos solo para mujeres / solo para hombres.
UPDATE NOM_DIAS_FESTIVOS SET APLICA_SEXO = 'F' WHERE FECHA_FESTIVO IN (DATE '2026-03-08', DATE '2026-05-10');
UPDATE NOM_DIAS_FESTIVOS SET APLICA_SEXO = 'M' WHERE FECHA_FESTIVO IN (DATE '2025-11-24', DATE '2026-11-23', DATE '2026-06-19');

-- Puentes: fecha oficial de los que se recorrieron.
UPDATE NOM_DIAS_FESTIVOS SET FECHA_OFICIAL = DATE '2025-02-05' WHERE FECHA_FESTIVO = DATE '2025-02-03';
UPDATE NOM_DIAS_FESTIVOS SET FECHA_OFICIAL = DATE '2026-02-05' WHERE FECHA_FESTIVO = DATE '2026-02-02';
UPDATE NOM_DIAS_FESTIVOS SET FECHA_OFICIAL = DATE '2025-03-21' WHERE FECHA_FESTIVO = DATE '2025-03-17';
UPDATE NOM_DIAS_FESTIVOS SET FECHA_OFICIAL = DATE '2026-03-21' WHERE FECHA_FESTIVO = DATE '2026-03-16';
UPDATE NOM_DIAS_FESTIVOS SET FECHA_OFICIAL = DATE '2025-11-02' WHERE FECHA_FESTIVO = DATE '2025-11-03';
UPDATE NOM_DIAS_FESTIVOS SET FECHA_OFICIAL = DATE '2025-11-20' WHERE FECHA_FESTIVO = DATE '2025-11-17';
UPDATE NOM_DIAS_FESTIVOS SET FECHA_OFICIAL = DATE '2026-11-20' WHERE FECHA_FESTIVO = DATE '2026-11-16';
UPDATE NOM_DIAS_FESTIVOS SET FECHA_OFICIAL = DATE '2026-06-21' WHERE FECHA_FESTIVO = DATE '2026-06-19';

COMMIT;
