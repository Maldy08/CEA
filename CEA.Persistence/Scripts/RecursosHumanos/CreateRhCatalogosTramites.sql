-- Los acentos van con UNISTR para no depender del NLS_LANG del cliente (la BD es WE8MSWIN1252).

CREATE TABLE RH_CAT_TIPOS_TRAMITE (
    ID_TIPO_TRAMITE NUMBER(2)               NOT NULL,
    NOMBRE_TRAMITE  VARCHAR2(50)            NOT NULL,
    ACTIVO          VARCHAR2(1) DEFAULT 'S' NOT NULL,
    CONSTRAINT PK_RH_CAT_TIPOS_TRAMITE PRIMARY KEY (ID_TIPO_TRAMITE),
    CONSTRAINT CK_RH_CAT_TIPOS_TRAM_ACTIVO CHECK (ACTIVO IN ('S', 'N'))
);

