-- Incapacidades (diseño "Diseño de Tablas para TRamites RH", pestaña nom_incapacidades). Tomada de la tabla vieja
-- NOM_INCAP (NOEMP, DIAS, TIPOINCA, TIPOENF, FDESDE, FHASTA, NOMUNIDAD, NOMMEDICO, OBSERVA; 1321 renglones
-- 2014-2025), que NO se toca ni se migra (por ahora la nueva empieza vacía). Mismos tipos de dato que NOM_INCAP, salvo DIAS NUMBER(3) y OBSERVA 500.
--
--   ID_TRAMITE        NULL cuando RH la captura directo sin pasar por el portal (ORIGEN_REGISTRO = 'R').
--                     Si viene del portal ('T') es obligatorio y único (un trámite tipo 5 = una incapacidad).
--   FOLIO_ISSSTECALI  folio de la incapacidad expedida por ISSSTECALI.
--   REGMEDICO         registro médico del empleado (como EMPLEADOS.REGMEDICO).
--   TIPOINCA          1 = INICIAL, 2 = SUBSECUENTE (como en NOM_INCAP).
--   TIPOENF           FK a NOM_INCAPCAT: 1 ENFERMEDAD GENERAL, 2 RIESGO DE TRABAJO,
--                     3 PROBABLE RIESGO DE TRABAJO, 4 MATERNIDAD.
--   DIAS              días naturales (en NOM_INCAP casi siempre FHASTA - FDESDE + 1).

CREATE TABLE NOM_INCAPACIDADES (
    ID_INCAPACIDAD   NUMBER(12)    NOT NULL,
    ID_TRAMITE       NUMBER(12),
    FOLIO_ISSSTECALI VARCHAR2(20),
    NOEMP            NUMBER(4)     NOT NULL,
    REGMEDICO        VARCHAR2(50),
    TIPOINCA         NUMBER(1)     NOT NULL,
    TIPOENF          NUMBER(2)     NOT NULL,
    NOMUNIDAD        VARCHAR2(100),
    FDESDE           DATE          NOT NULL,
    FHASTA           DATE          NOT NULL,
    DIAS             NUMBER(3)     NOT NULL,
    NOMMEDICO        VARCHAR2(100),
    ORIGEN_REGISTRO  VARCHAR2(1)   DEFAULT 'T' NOT NULL,
    OBSERVA          VARCHAR2(500),
    CONSTRAINT PK_NOM_INCAPACIDADES PRIMARY KEY (ID_INCAPACIDAD),
    CONSTRAINT UK_NOM_INCAPACIDADES_TRAMITE UNIQUE (ID_TRAMITE),
    CONSTRAINT FK_NOM_INCAPACIDADES_TRAMITE FOREIGN KEY (ID_TRAMITE) REFERENCES NOM_TRAMITES (ID_TRAMITE),
    CONSTRAINT FK_NOM_INCAPACIDADES_EMP FOREIGN KEY (NOEMP) REFERENCES EMPLEADOS (EMPLEADO),
    CONSTRAINT FK_NOM_INCAPACIDADES_TIPOENF FOREIGN KEY (TIPOENF) REFERENCES NOM_INCAPCAT (ID),
    CONSTRAINT CK_NOM_INCAPACIDADES_TIPOINCA CHECK (TIPOINCA IN (1, 2)),
    CONSTRAINT CK_NOM_INCAPACIDADES_FECHAS CHECK (FHASTA >= FDESDE),
    CONSTRAINT CK_NOM_INCAPACIDADES_DIAS CHECK (DIAS > 0),
    CONSTRAINT CK_NOM_INCAPACIDADES_ORIGEN CHECK (
        (ORIGEN_REGISTRO = 'T' AND ID_TRAMITE IS NOT NULL)
     OR (ORIGEN_REGISTRO = 'R' AND ID_TRAMITE IS NULL))
);

CREATE UNIQUE INDEX UX_NOM_INCAPACIDADES_FOLIO ON NOM_INCAPACIDADES (FOLIO_ISSSTECALI);
CREATE INDEX IX_NOM_INCAPACIDADES_EMP ON NOM_INCAPACIDADES (NOEMP, FDESDE);

CREATE SEQUENCE SEQ_NOM_INCAPACIDADES START WITH 1 INCREMENT BY 1 NOCACHE;

CREATE OR REPLACE TRIGGER TRG_NOM_INCAPACIDADES_BI
BEFORE INSERT ON NOM_INCAPACIDADES
FOR EACH ROW
WHEN (NEW.ID_INCAPACIDAD IS NULL)
BEGIN
    SELECT SEQ_NOM_INCAPACIDADES.NEXTVAL INTO :NEW.ID_INCAPACIDAD FROM DUAL;
END;
/

COMMENT ON TABLE NOM_INCAPACIDADES IS 'Incapacidades ISSSTECALI: trámite del portal (tipo 5) o captura directa de RH';
COMMENT ON COLUMN NOM_INCAPACIDADES.ID_TRAMITE IS 'NOM_TRAMITES; NULL si ORIGEN_REGISTRO = R';
COMMENT ON COLUMN NOM_INCAPACIDADES.TIPOINCA IS '1 = INICIAL, 2 = SUBSECUENTE';
COMMENT ON COLUMN NOM_INCAPACIDADES.TIPOENF IS 'NOM_INCAPCAT.ID';
COMMENT ON COLUMN NOM_INCAPACIDADES.ORIGEN_REGISTRO IS 'T = trámite del portal, R = captura directa de RH';
